// Regenerates TEACHER_REVIEW.md from data: rule glosses, waqf signs, special Hafs words (found by pattern in the
// Tanzil text), two-source disputes, and every model-knowledge item in the lesson JSON.
// Quran words shown here are read from the shipped Tanzil text, never typed.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { RULES } from '../src/data/rules.ts';
import { PAUSE_MARKS } from '../src/data/quranText.ts';

const ROOT = resolve(import.meta.dirname, '..');
const lines = new Map<string, string>();
for (const l of readFileSync(join(ROOT, 'data/source/tanzil/quran-uthmani.txt'), 'utf8').split('\n')) {
  const p = l.split('|');
  if (p.length === 3) lines.set(`${p[0]}:${p[1]}`, p[2]!);
}
const wordAt = (k: string, off: number) => {
  const t = lines.get(k) ?? '';
  let acc = 0;
  for (const w of t.split(' ')) {
    if (off >= acc && off < acc + w.length) return w;
    acc += w.length + 1;
  }
  return '';
};
const findWords = (re: RegExp) => {
  const out: [string, string][] = [];
  for (const [k, t] of lines) for (const w of t.split(' ')) if (re.test(w)) out.push([k, w]);
  return out;
};

const md: string[] = [];
const push = (...x: string[]) => md.push(...x);

// ---------- lessons: model-knowledge items ----------
interface Prov { kind: 'dataset' | 'reference' | 'model-knowledge'; source?: string }
const lessonDir = join(ROOT, 'src/content/lessons');
const mk: { lesson: string; field: string; text: string }[] = [];
if (existsSync(lessonDir)) {
  for (const f of readdirSync(lessonDir).filter((x) => x.endsWith('.json')).sort()) {
    const L = JSON.parse(readFileSync(join(lessonDir, f), 'utf8')) as Record<string, unknown> & { id: string; reviewStatus?: string };
    if (L.reviewStatus === 'teacher-approved') continue;
    const walk = (node: unknown, path: string) => {
      if (Array.isArray(node)) node.forEach((x, i) => walk(x, `${path}[${i}]`));
      else if (node && typeof node === 'object') {
        const o = node as Record<string, unknown> & { provenance?: Prov; text?: string };
        if (o.provenance?.kind === 'model-knowledge') mk.push({ lesson: L.id, field: path, text: String(o.text ?? o.q ?? o.term ?? JSON.stringify(o).slice(0, 160)) });
        for (const [k, v] of Object.entries(o)) if (k !== 'provenance') walk(v, `${path}.${k}`);
      }
    };
    walk(L, '');
  }
}

